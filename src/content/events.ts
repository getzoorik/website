/** The Where filter's places: an event in India, or one you can follow online (virtual or hybrid). */
export type EventPlace = "india" | "online";

/**
 * One event, as the radar's list writes it (its public fields only, the keys in camelCase). Dates are ISO:
 * `startDate` is a day ("2026-11-09") or, while the organizer has announced only the month, a month ("2027-04"),
 * and then `endDate` is empty. An empty string is a fact the organizer's page does not give.
 */
export interface EventEntry {
  readonly name: string;
  readonly organizer: string;
  readonly topic: EventTopic;
  readonly startDate: string;
  /** The last day; empty for a one-day event or a month-only one. */
  readonly endDate: string;
  readonly dateStatus: "confirmed" | "announced month";
  readonly city: string;
  readonly country: string;
  readonly venue: string;
  readonly format: "in person" | "hybrid" | "virtual";
  readonly description: string;
  readonly whyItMatters: string;
  /** The organizer's public event page: the only address the page links an event to. */
  readonly officialUrl: string;
  /**
   * The organizer's own site, for the Event markup's organizer only (the page prints none): the list's
   * `organizer_url`, opened and seen to be that organizer (local organizers' own site where they have one, else a
   * KCD's chapter page on community2.cncf.io), never a sign-in page and never guessed from the event's page. Left
   * out where the list gives none.
   */
  readonly organizerUrl?: string;
  /** The call for talks, in the list's words; empty when the page says nothing of one. */
  readonly cfp: string;
  /** The ticket label, never a price; empty when the list gives none, and then the page shows none. */
  readonly tickets:
    | ""
    | "Free"
    | "Paid"
    | "Members only"
    | "Invitation or approval needed"
    | "Free online, paid in person";
}

